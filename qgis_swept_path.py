    def _reset_vehicle(self):
        # Uncheck vehicle status and delete vehicle
        self.dockwidget.chbCreateVehicle.setChecked(False)
        self.dockwidget.chbPlaceVehicle.setChecked(False)
        self._disconnect_vehicle_signals()
        self.vehicle = None


    def _setup_vehicle(self):
        self.dockwidget.chbCreateVehicle.setChecked(False)
        self.dockwidget.chbPlaceVehicle.setChecked(False)
        self._vehicle_features.clear()
        selected_vehicle_name: str = self.dockwidget.cmboVehicleSelect.currentText()
        vehicle_item: tuple[str, str] = self._vehicle_list[selected_vehicle_name]

        vehicle_module = __import__(vehicle_item[1], fromlist=[vehicle_item[0]])
        vehicle_class = getattr(vehicle_module, vehicle_item[0])

        self._disconnect_vehicle_signals()
        self.vehicle = vehicle_class()
        self._connect_vehicle_signals()

        self.dockwidget.chbCreateVehicle.setChecked(True)


    def _connect_vehicle_signals(self):
        # Connects the signals for all child vehicles
        for v in self.vehicle.vehicle_parts:
            v.pauseSimulation.connect(self._vehicle_paused_simulation)
            v.stopSimulation.connect(self._vehicle_stopped_simulation)


    def _disconnect_vehicle_signals(self):
        # Disconnects the signals for all child vehicles
        if isinstance(self.vehicle, Vehicle):
            for v in self.vehicle.vehicle_parts:
                v.pauseSimulation.disconnect(self._vehicle_paused_simulation)
                v.stopSimulation.disconnect(self._vehicle_stopped_simulation)


    def _place_vehicle(self):
        # Place the vehicle with the VehiclePlacer class
        if self._vehicle_layer is None:
            self.iface.messageBar().pushMessage(
                "Can't place vehicle",
                "The vehicle layer must first be created or be set in the properties",
                level=Qgis.Critical)
        elif self.vehicle is None:
            self.iface.messageBar().pushMessage(
                "Can't place vehicle",
                "The vehicle must first be created",
                level=Qgis.Critical)
        else:
            self._vehicle_placer = VehiclePlacer(self.iface, self.vehicle)  # Tool for placing vehicle
            self._vehicle_placer.placed.connect(self._vehicle_placed)
            self._vehicle_placer.aborted.connect(self._place_vehicle_aborted)
            self.canvas.setMapTool(self._vehicle_placer)
            self.canvas.setFocus(Qt.OtherFocusReason)


    def _vehicle_placed(self):
        # Unset the VehiclePlacer and draw the vehicle
        # Method is called, when the VehiclePlacer is finish
        self.canvas.unsetMapTool(self._vehicle_placer)
        self.iface.actionPan().trigger()
        self._undo_stack.clear()
        self._create_vehicle_drawing()
        self.dockwidget.chbPlaceVehicle.setChecked(True)


    def _place_vehicle_aborted(self):
        # Unset the VechiclePlacer an exit
        # Method is called, when the VehiclePlacer is aborted
        self.canvas.unsetMapTool(self._vehicle_placer)
        self.iface.actionPan().trigger()

        self.iface.messageBar().pushMessage(
            "Exit vehicle placement",
            "No vehicle placed",
            level=Qgis.Info)


    def _draw_vehicle(self):
        self._vehicle_layer.dataProvider().truncate()
        for v, f in self._vehicle_features.items():
            f["rotation"] = CoordUtils.rad_to_degrees(v.a) * -1
            f["wheel_angle"] = CoordUtils.rad_to_degrees(v.steering_angle)
            f.setGeometry(QgsGeometry.fromPointXY(QgsPointXY(v.f.x, v.f.y)))
            self._vehicle_layer.dataProvider().addFeatures([f])

        if self.prop.auto_map_movement and self._vehicle_reached_edge():
            self.canvas.setCenter(QgsPointXY(self.vehicle.f.x, self.vehicle.f.y))

        self._vehicle_layer.triggerRepaint()

        self.update_speed()
        self.update_steering()


    def _create_vehicle_drawing(self):
        self._vehicle_layer.dataProvider().truncate()
        for v in self.vehicle.vehicle_parts:
            feature = QgsFeature(self._vehicle_layer.fields())
            feature["symbol"] = v.get_symbol_path()
            feature["rotation"] = CoordUtils.rad_to_degrees(v.a) * -1
            feature["size_x"] = v.symbol_size_x
            feature["size_y"] = v.symbol_size_y
            feature["offset_x"] = v.symbol_offset_x
            feature["offset_y"] = v.symbol_offset_y
            feature["wheel_angle"] = CoordUtils.rad_to_degrees(v.steering_angle)
            feature.setGeometry(QgsGeometry.fromPointXY(QgsPointXY(v.f.x, v.f.y)))
            self._vehicle_features[v] = feature

            self._vehicle_layer.dataProvider().addFeatures([feature])

        self._vehicle_layer.triggerRepaint()


    def _store_path_points(self):
        # Store the vehicle points in a list
        for p in self._path_points:
            p.add_point(getattr(p.vehicle, p.vehicle_part))


    def _write_path_to_layer(self) -> list:
        # Write the stored points as lines to the layer; returns the new feature ids
        feature_ids = []
        for p in self._path_points:
            feature = QgsFeature(self._path_layer.fields())
            feature["simulation_id"] = self._simulation_id
            feature["vehicle_name"] = p.vehicle_name
            feature["vehicle_type"] = p.vehicle_type
            feature["vehicle_part_type"] = p.vehicle_part_type
            feature["vehicle_part"] = p.vehicle_part
            feature.setGeometry(QgsGeometry.fromPolylineXY(p.get_list_as_qgs_points()))
            ok, added = self._path_layer.dataProvider().addFeatures([feature])
            if ok:
                feature_ids.extend(f.id() for f in added)
        self._path_layer.reload()
        self._path_layer.triggerRepaint()
        return feature_ids
    def _begin_undo_entry(self):
        # Snapshot taken just before a run starts
        self._undo_pending = {
            "vehicle": self.vehicle,
            "state": capture_vehicle_state(self.vehicle),
            "simulation_id": self._simulation_id,
            "path_layer_id": None,
            "feature_ids": [],
        }

    def _commit_undo_entry(self, path_layer_id, feature_ids):
        entry = self._undo_pending
        self._undo_pending = None
        if entry is None:
            return
        entry["path_layer_id"] = path_layer_id
        entry["feature_ids"] = list(feature_ids)
        self._undo_stack.append(entry)
        del self._undo_stack[:-self.UNDO_LIMIT]

    def undo_last_run(self):
        """Undo the last run: delete its swept path and put the vehicle back where it started."""
        if self.simulator is not None and self.simulator.simulation_running:
            self.stopSimulation()  # discard the run in progress

        bar = self.iface.messageBar()
        if not self._undo_stack:
            bar.pushMessage("Undo", "Nothing to undo.", level=Qgis.Info, duration=3)
            return

        entry = self._undo_stack.pop()
        if entry["vehicle"] is not self.vehicle:
            self._undo_stack.clear()
            bar.pushMessage("Undo", "The vehicle has changed since that run, nothing to undo.",
                            level=Qgis.Info, duration=4)
            return

        # 1. Remove the swept path written by that run
        removed = 0
        layer = self.proj.mapLayer(entry["path_layer_id"]) if entry["path_layer_id"] else None
        if layer is not None:
            ids = list(entry["feature_ids"])
            if not ids and entry["simulation_id"]:
                ids = [f.id() for f in layer.getFeatures()
                       if f["simulation_id"] == entry["simulation_id"]]
            if ids and layer.dataProvider().deleteFeatures(ids):
                removed = len(ids)
                layer.reload()
                layer.triggerRepaint()

        # 2. Put the vehicle back
        ok, details = apply_vehicle_state(entry["state"])

        self._vehicle_features.clear()
        try:
            self._create_vehicle_drawing()
        except (AttributeError, RuntimeError):
            bar.pushMessage("Undo", "Vehicle layer is not available, so the vehicle was not redrawn.",
                            level=Qgis.Warning, duration=5)
        self.update_speed()
        self.update_steering()

        if ok:
            bar.pushMessage("Undo", "Last run undone ({} path features removed).".format(removed),
                            level=Qgis.Success, duration=3)
        else:
            print("QgisSweptPath undo: " + details)
            bar.pushMessage("Undo",
                            "Swept path removed, but the vehicle position could not be fully restored. "
                            + details,
                            level=Qgis.Warning, duration=0)

    def _on_route_failed(self, reason: str):
        # The simulator stopped the vehicle because the route can't be driven
        self._route_tool.reset()
        if self.simulator is not None and self.simulator.simulation_running:
            self.stopSimulation()

        bar = self.iface.messageBar()
        widget = bar.createMessage("Route not possible", reason)
        button = QPushButton(widget)
        button.setText("Undo run")
        widget.layout().addWidget(button)
        item = bar.pushWidget(widget, Qgis.Warning, 0)
        button.clicked.connect(lambda _checked=False: self._undo_from_message(item))

    def _undo_from_message(self, item):
        self.undo_last_run()
        try:
            self.iface.messageBar().popWidget(item)
        except Exception:
            pass
    def _create_vehicle_layer(self):
        """
        Create a new in memory vector layer to show the vehicle during simulation
        """
        if self.dockwidget.chbVehicleLayer.isChecked():
            self.iface.messageBar().pushMessage(
                "Vehicle layer already exists",
                "To create a new vehicle layer uncheck this option first",
                level=Qgis.Info
            )
            return

        if self._vehicle_layer is not None:
            # Print the message, when the vehicle layer already exists
            self.iface.messageBar().pushMessage(
                "New vehicle Layer",
                "A new vehicle layer is created and saved in this project",
                level=Qgis.Info
            )

        # Create new vector layer and set Crs to project crs
        self._vehicle_layer = self.iface.addVectorLayer("Point", "vehicle", "memory")
        crs = self.proj.crs()
        self._vehicle_layer.setCrs(crs)

        # Add the attributes
        self._vehicle_layer.dataProvider().addAttributes([QgsField("symbol", QVariant.String)])
        self._vehicle_layer.dataProvider().addAttributes([QgsField("rotation", QVariant.Double)])
        self._vehicle_layer.dataProvider().addAttributes([QgsField("size_x", QVariant.Double)])
        self._vehicle_layer.dataProvider().addAttributes([QgsField("size_y", QVariant.Double)])
        self._vehicle_layer.dataProvider().addAttributes([QgsField("offset_x", QVariant.Double)])
        self._vehicle_layer.dataProvider().addAttributes([QgsField("offset_y", QVariant.Double)])
        self._vehicle_layer.dataProvider().addAttributes([QgsField("wheel_angle", QVariant.Double)])
        self._vehicle_layer.updateFields()

        # Add layer as new map layer
        self.proj.addMapLayer(self._vehicle_layer)

        # Save the id of the map layer in the project and show the id in the text field
        self.prop.set_vehicle_layer_id(self._vehicle_layer.id())

        # Add signal for layer delete
        self._vehicle_layer.willBeDeleted.connect(self._vehicle_layer_delete)

        # Set default style
        self._set_default_vehicle_layer_style()

        # Lock vehicle layer
        self.dockwidget.chbVehicleLayer.setChecked(True)


    def _create_path_layer(self):
        """
        Create a new vector layer to print the paths
        """
        if self.dockwidget.chbPathLayer.isChecked():
            self.iface.messageBar().pushMessage(
                "Path layer already exists",
                "To create a new path layer uncheck this option first",
                level=Qgis.Info
            )
            return

        if self._path_layer is not None:
            # Print the message, when the path layer already exists
            self.iface.messageBar().pushMessage(
                "New path layer",
                "A new path layer is created and saved in this project",
                level=Qgis.Info
            )

        self._path_layer = self.iface.addVectorLayer("LineString", "path", "memory")
        crs = self.proj.crs()
        self._path_layer.setCrs(crs)

        # Add the attributes
        self._path_layer.dataProvider().addAttributes([QgsField("simulation_id", QVariant.String)])
        self._path_layer.dataProvider().addAttributes([QgsField("vehicle_name", QVariant.String)])
        self._path_layer.dataProvider().addAttributes([QgsField("vehicle_type", QVariant.String)])
        self._path_layer.dataProvider().addAttributes([QgsField("vehicle_part_type", QVariant.String)])
        self._path_layer.dataProvider().addAttributes([QgsField("vehicle_part", QVariant.String)])
        self._path_layer.updateFields()

        # Add layer as new map layer
        self.proj.addMapLayer(self._path_layer)

        # Save the id of the map layer in the project and show the id in the text field
        self.prop.set_path_layer_id(self._path_layer.id())

        # Add signal for layer delete
        self._path_layer.willBeDeleted.connect(self._path_layer_delete)

        # Set default style
        self._set_default_path_layer_style()

        # Show dialog to save the path layer to file/database
        save_dialog = QgsVectorLayerSaveAsDialog(self._path_layer, QgsVectorLayerSaveAsDialog.Option.Symbology)
        if save_dialog.exec():
            # If dialog returns true
            save_options = QgsVectorFileWriter.SaveVectorOptions()  # Create save options
            save_options.layerName = save_dialog.layerName()  # Set layer name
            transform_context = self.proj.transformContext()  # Transform context
            # Save layer to file
            writer_error = QgsVectorFileWriter.writeAsVectorFormatV3(self._path_layer,
                                                              save_dialog.fileName(),
                                                              transform_context,
                                                              save_options)

            if writer_error[0] == QgsVectorFileWriter.NoError:
                # When saved successfully, set the data source to the saved layer
                self._path_layer.setDataSource(
                    "{}|layername={}".format(save_dialog.fileName(), save_dialog.layerName()),
                    self._path_layer.name(),
                    'ogr')

            else:
                # On error show message and keep local layer
                self.iface.messageBar().pushWarning(
                    "Local path layer",
                    "Path layer could not be saved to file. Only a memory layer is created. All geometries will be lost"
                    "when the project is closed. The created layer must be saved manually",
                )
        else:
            # On error or when canceled show message and keep local layer
            self.iface.messageBar().pushWarning(
                "Local path layer",
                "Path layer could not be saved to file. Only a memory layer is created. All geometries will be lost"
                "when the project is closed. The created layer must be saved manually",
            )

        # Lock path layer
        self.dockwidget.chbPathLayer.setChecked(True)


